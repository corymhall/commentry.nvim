describe("commentry.setup", function()
  it("keeps setup idempotent without loading a review store or agent adapter", function()
    local config = { keymaps = { list_comments = "gl" } }
    require("commentry").setup(config)
    local before = vim.api.nvim_get_autocmds({ group = require("commentry.config").augroup })
    require("commentry").setup(config)
    local after = vim.api.nvim_get_autocmds({ group = require("commentry.config").augroup })
    assert.are.same(#before, #after)
    assert.are.same("gl", require("commentry.config").keymaps.list_comments)
  end)
end)
